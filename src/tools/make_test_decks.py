#!/usr/bin/env python3
"""Build test decks for play-testing new cards.

Usage: make_test_decks.py Manalink.csv tests/decks PLAYDECK_DIR

Each tests/decks/NAME.txt holds "COUNT Card Name" lines ('#' starts a comment), and
becomes PLAYDECK_DIR/test-NAME.dck, which Magic.exe lists among its decks.  Card names
are looked up in Manalink.csv, so a deck stops building if a card is renamed or its id
changes - .dck files store csvids, which is exactly what goes stale otherwise.
"""

import csv
import os
import sys


def main():
    sys.stdout.reconfigure(errors="backslashreplace")
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    manalink, deck_dir, out_dir = sys.argv[1:]
    ids = {}
    with open(manalink, newline="", encoding="latin-1") as f:
        for row in csv.reader(f, delimiter=";"):
            if row and row[0].strip().isdigit():
                ids.setdefault(row[1], int(row[0]))

    for txt in sorted(os.listdir(deck_dir)):
        if not txt.endswith(".txt"):
            continue
        name = txt[:-4]
        lines = [";test-%s" % name, ";Generated by tools/make_test_decks.py from tests/decks/%s" % txt, ""]
        total = 0
        with open(os.path.join(deck_dir, txt), encoding="latin-1") as f:
            for line in f:
                line = line.split("#", 1)[0].strip()
                if not line:
                    continue
                count, card = line.split(None, 1)
                if card not in ids:
                    sys.exit("%s: %r isn't in Manalink.csv" % (txt, card))
                lines.append(".%d\t%s\t%s" % (ids[card], count, card))
                total += int(count)
        path = os.path.join(out_dir, "test-%s.dck" % name)
        with open(path, "w", encoding="latin-1", newline="\r\n") as f:
            f.write("\n".join(lines) + "\n")
        print("%s: %d cards" % (path, total))


if __name__ == "__main__":
    main()
